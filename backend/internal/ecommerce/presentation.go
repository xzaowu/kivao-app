package ecommerce

import "strings"

const layoutSafetyRule = "【最终画幅与排版】背景和场景连续延伸到画幅四边，不额外套白框或黑条。有文字、标签、卡片、图标或引线时，其完整外框（含描边、阴影和旋转后的四角）须落在四边各内缩至少 8% 的安全区，横纵坐标为 8%–92%。保留约 20%–30% 不承载文字和装饰的呼吸空间，留白沿用本套背景；文字与商品、不同信息组互相避让。单屏有文案时只安排一个主标题和一组辅助信息，短标签最多 3 个，说明卡片或局部放大窗最多 2 个，不重复堆叠。长标题主动换行，空间不足时移动文字、卡片或商品并重排构图，不裁字、不截断文案、不用极小字号硬塞。生成阶段完整保留已审阅文案原文；没有文案时保持无新增文字的画面。以上仅为执行规则，不得作为图中可见文字。"

const humanPhotographyRule = "【人物摄影】只有商品用途、已选构图或明确用户要求需要时安排人物，不强制每张出现模特；用户不要人物时不添加。真人保持符合年龄和景别的自然肤纹、色差、发丝与表情，近景保留细节，中远景不过度锐化，不磨皮成蜡像或塑料脸。手指、关节、握持、遮挡及与商品接触的关系自然，人物、商品和背景的光向、尺度与接触阴影一致。同一套中已明确的人物设定保持一致，不在单张重做时随机换脸；未指定市场和人物资料时不根据平台或语言推断国籍、族裔或真人身份。明确要求陈列假人时保持假人的材质与结构，不添加真人皮肤。"

func ImagePrompt(draft Draft, image Image) string {
	textRule := "【已审阅文案】只将上图文案原文用于新增的图中文字，保留其语言、空格、标点与换行，不擅自添加卖点、缩短或改写。方案标题、参考图用途、JSON 字段名和执行说明不作为图中文字。"
	if strings.TrimSpace(image.Copy) == "" {
		textRule = "【无新增文案】上图文案为空，不额外添加标题、卖点、营销标签或水印；商品本身真实的 Logo 与包装印刷保留。方案标题、参考图用途和执行说明不作为图中文字。"
	}
	return strings.Join([]string{
		image.Prompt,
		"上图文案：" + image.Copy,
		ReferenceRoles(draft),
		"以商品原图保持商品身份、Logo 与原色，参考图的背景不必复制。不得添加未证实的参数或功效。",
		humanPhotographyRule,
		textRule,
		layoutSafetyRule,
	}, "\n")
}
